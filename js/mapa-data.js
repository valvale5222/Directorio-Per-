  /* ── 6 · AGREGACIONES ────────────────────────────────────────*/

  function sum(a)        { return a.reduce(function (t, r) { return t + r.imp; }, 0); }
  function sumMg(a)      { return a.reduce(function (t, r) { return t + r.mg; }, 0); }
  function nClientes(a)  { var s = {}; a.forEach(function (r) { if (r.clienteKey) s[r.clienteKey] = 1; }); return Object.keys(s).length; }
  function nProyectos(a) { var s = {}; a.forEach(function (r) { if (r.cod) s[r.cod] = 1; }); return Object.keys(s).length; }

  /** Margen ponderado: Σmargen$ / Σimporte. */
  function margen(a) { var v = sum(a); return v > 0 ? sumMg(a) / v : 0; }

  /** Agrupa por una clave y devuelve el ranking DESC con participación. */
  function ranking(arr, keyFn, labelFn) {
    var total = sum(arr), map = {}, orden = [];
    arr.forEach(function (r) {
      var k = keyFn(r); if (k == null || k === '') return;
      if (!map[k]) { map[k] = { key: k, label: labelFn ? labelFn(r) : k, imp: 0, mg: 0, n: 0, cods: {}, clis: {}, deps: {} }; orden.push(k); }
      map[k].imp += r.imp; map[k].mg += r.mg; map[k].n++;
      if (r.cod) map[k].cods[r.cod] = 1;
      if (r.clienteKey) map[k].clis[r.clienteKey] = 1;
      if (r.dep) map[k].deps[r.depLabel] = (map[k].deps[r.depLabel] || 0) + r.imp;
    });
    return orden.map(function (k) {
      var o = map[k];
      /* Departamento dominante del grupo (para la tabla de clientes). */
      var dep = Object.keys(o.deps).sort(function (a, b) { return o.deps[b] - o.deps[a]; })[0] || '';
      return {
        key: o.key, label: o.label, imp: o.imp, registros: o.n,
        proyectos: Object.keys(o.cods).length,
        clientes:  Object.keys(o.clis).length,
        margen:    o.imp > 0 ? o.mg / o.imp : 0,
        dep:       dep,
        part: total > 0 ? o.imp / total : 0
      };
    }).sort(function (a, b) { return b.imp - a.imp; });
  }

  /** Filtro base: año obligatorio; zona y departamento opcionales. */
  function filtrar(anio, zona, dep) {
    return ROWS.filter(function (r) {
      if (r.anio !== anio) return false;
      if (zona && r.zona !== zona) return false;
      if (dep && r.dep !== dep) return false;
      return true;
    });
  }

  /** Totales nacionales del año + participación de cada zona. */
  function zonas(anio) {
    var todo = filtrar(anio), total = sum(todo);
    return {
      total: total,
      margen: margen(todo),
      clientes: nClientes(todo),
      proyectos: nProyectos(todo),
      lista: ZONAS.map(function (z) {
        var a = todo.filter(function (r) { return r.zona === z; });
        var imp = sum(a);
        return {
          key: z, label: ZONA_LABEL[z], imp: imp,
          part: total > 0 ? imp / total : 0,
          margen: margen(a),
          clientes: nClientes(a), proyectos: nProyectos(a),
          deps: ranking(a, function (r) { return r.dep; }, function (r) { return r.depLabel; })
        };
      })
    };
  }

  /** Departamentos de una zona/año, con % dentro de la zona. */
  function departamentos(anio, zona) {
    return ranking(filtrar(anio, zona), function (r) { return r.dep; }, function (r) { return r.depLabel; });
  }

